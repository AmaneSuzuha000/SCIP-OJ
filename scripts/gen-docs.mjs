/**
 * Turn the published course documents into a typed module.
 *
 * docs/ is staged next to the app, but nothing in the app could open it: the
 * files were reachable only by guessing a URL. Bundling the text at build time
 * keeps one source of truth (the markdown in docs/) and gives the app a real
 * reader route.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const DOCS = resolve(ROOT, 'docs');
const OUT = resolve(ROOT, 'web/src/features/docs/documents.ts');

// Same list the deploy uses, so the reader never shows something the build
// would refuse to publish, and never hides something it does.
//
// Four documents were removed: the teacher guide, the exam-roster handbook and
// the authoring guide all described the retired portal (its /teacher.html, its
// tabs, its buttons), and the grading protocol still said "L1 only, L2 later"
// long after container grading shipped. Publishing instructions for screens
// that no longer exist is worse than publishing nothing.
const DOCUMENTS = [
  { id: 'student-guide', file: '学生指南.md', group: 'student' },
  { id: 'learning-path', file: '课程学习路径.md', group: 'student' },
  { id: 'extended-guide', file: '拓展学习指南.md', group: 'student' },
  { id: 'grading-rules', file: '课程实验与评价规范.md', group: 'case' },
];

/** The card shows plain text, so inline markdown must not leak into it. */
function plain(text) {
  return text
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\`([^\`]+)\`/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .trim();
}

function describe(text) {
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#') || line.startsWith('|') || line.startsWith('>')) continue;
    if (/^[-*]\s/.test(line) || /^\d+[.)]\s/.test(line)) continue;
    return plain(line);
  }
  return '';
}

const parts = [];
for (const doc of DOCUMENTS) {
  const text = await readFile(resolve(DOCS, doc.file), 'utf8');
  const heading = /^#\s+(.+)$/m.exec(text);
  const title = (heading ? heading[1] : doc.file.replace(/\.md$/, '')).trim();
  const body = JSON.stringify(text);
  parts.push(
    [
      '  {',
      '    id: ' + JSON.stringify(doc.id) + ',',
      '    group: ' + JSON.stringify(doc.group) + ',',
      '    title: ' + JSON.stringify(title) + ',',
      '    summary: ' + JSON.stringify(describe(text)) + ',',
      '    source: ' + body + ',',
      '  },',
    ].join('\n'),
  );
}

const file = [
  '// Generated by scripts/gen-docs.mjs. Edit the markdown in docs/, not this file.',
  '',
  "export type DocGroup = 'student' | 'teacher' | 'case';",
  '',
  'export interface Doc {',
  '  id: string;',
  '  group: DocGroup;',
  '  title: string;',
  '  summary: string;',
  '  source: string;',
  '}',
  '',
  'export const DOC_GROUP_LABEL: Record<DocGroup, string> = {',
  "  student: '学生',",
  "  teacher: '教师',",
  "  case: '案例与规范',",
  '};',
  '',
  'export const DOCUMENTS: Doc[] = [',
  parts.join('\n'),
  '];',
  '',
  'export function findDoc(id: string | undefined): Doc | undefined {',
  '  return DOCUMENTS.find((doc) => doc.id === id);',
  '}',
  '',
].join('\n');

await writeFile(OUT, file, 'utf8');
const total = DOCUMENTS.length;
console.log('已生成 ' + total + ' 篇文档 -> web/src/features/docs/documents.ts');
