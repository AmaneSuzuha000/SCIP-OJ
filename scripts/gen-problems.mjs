/**
 * Bundle the problem statements so the workbench can show them.
 *
 * The statements are published under /problems/, but nothing in the app could
 * reach them: a student opening an assignment saw an empty editor with no
 * indication of what to solve. Bundling the text keeps the markdown in
 * problems/ as the single source of truth.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, 'web/src/features/problems/statements.ts');

const index = JSON.parse(await readFile(resolve(ROOT, 'problems/index.json'), 'utf8'));

const parts = [];
for (const entry of index) {
  const file = resolve(ROOT, entry.path, 'README.md');
  let source = '';
  try {
    source = await readFile(file, 'utf8');
  } catch {
    console.warn('缺少题面: ' + entry.path);
    continue;
  }
  let template = '';
  try {
    template = await readFile(resolve(ROOT, entry.path, 'template.py'), 'utf8');
  } catch {
    template = '';
  }
  parts.push(
    [
      '  {',
      '    id: ' + JSON.stringify(entry.id) + ',',
      '    title: ' + JSON.stringify(entry.title) + ',',
      '    difficulty: ' + JSON.stringify(entry.difficulty) + ',',
      '    tags: ' + JSON.stringify(entry.tags ?? []) + ',',
      '    source: ' + JSON.stringify(source) + ',',
      '    template: ' + JSON.stringify(template) + ',',
      '  },',
    ].join('\n'),
  );
}

const file = [
  '// Generated by scripts/gen-problems.mjs. Edit problems/*/README.md, not this file.',
  '',
  'export interface Statement {',
  '  id: string;',
  '  title: string;',
  '  difficulty: string;',
  '  tags: string[];',
  '  source: string;',
  '  template?: string;',
  '}',
  '',
  'export const STATEMENTS: Statement[] = [',
  parts.join('\n'),
  '];',
  '',
  'export function findStatement(problemId: string | undefined): Statement | undefined {',
  '  return STATEMENTS.find((entry) => entry.id === problemId);',
  '}',
  '',
].join('\n');

await writeFile(OUT, file, 'utf8');
console.log('已生成 ' + parts.length + ' 份题面 -> web/src/features/problems/statements.ts');
