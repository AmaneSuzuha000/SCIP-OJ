/**
 * Turn the course notebooks into a typed module the app imports.
 *
 * The notebooks are the source of truth -- the graders read the same files --
 * so they are compiled in rather than fetched. At 84 KB total that is cheaper
 * than fetching each one on demand, and it lets a lesson page render its
 * outline before the Python runtime finishes downloading.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const CONTENT = join(ROOT, 'content');
const TARGET = join(ROOT, 'web', 'src', 'features', 'notebook', 'lessons.ts');

/** Pull the first heading and the first paragraph of prose out of a notebook. */
function describe(cells) {
  let title = '';
  let summary = '';
  for (const cell of cells) {
    if (cell.kind !== 'markdown') continue;
    for (const line of cell.source.split('\n')) {
      const heading = /^#\s+(.+)$/.exec(line);
      if (heading && !title) {
        title = heading[1].trim();
        continue;
      }
      const text = line.trim();
      if (title && text && !text.startsWith('#') && !text.startsWith('-') && !summary) {
        summary = text;
      }
    }
    if (title && summary) break;
  }
  return { title, summary };
}

function toCells(notebook) {
  const cells = [];
  for (const cell of notebook.cells ?? []) {
    if (cell.cell_type !== 'markdown' && cell.cell_type !== 'code') continue;
    const source = Array.isArray(cell.source) ? cell.source.join('') : String(cell.source ?? '');
    if (!source.trim()) continue;
    cells.push({ kind: cell.cell_type, source });
  }
  return cells;
}

const files = (await readdir(CONTENT)).filter((name) => name.endsWith('.ipynb')).sort();
if (files.length === 0) {
  console.error('content/ 下没有 notebook，无法生成课程数据');
  process.exit(1);
}

const lessons = [];
for (const file of files) {
  const notebook = JSON.parse(await readFile(join(CONTENT, file), 'utf8'));
  const cells = toCells(notebook);
  const { title, summary } = describe(cells);
  lessons.push({
    id: file.replace(/\.ipynb$/, ''),
    file,
    title: title || file,
    summary,
    cells,
  });
}

const header = [
  '// Generated by scripts/gen-lessons.mjs -- do not edit by hand.',
  '// Source of truth: content/*.ipynb (the same files the graders use).',
  '',
  'export interface LessonCell {',
  "  kind: 'markdown' | 'code';",
  '  source: string;',
  '}',
  '',
  'export interface Lesson {',
  '  id: string;',
  '  file: string;',
  '  title: string;',
  '  summary: string;',
  '  cells: LessonCell[];',
  '}',
  '',
].join('\n');

const body = 'export const lessons: Lesson[] = ' + JSON.stringify(lessons, null, 2) + ';\n';
await writeFile(TARGET, header + body, 'utf8');

console.log('已生成 ' + lessons.length + ' 课 -> web/src/features/notebook/lessons.ts');
for (const lesson of lessons) console.log('  ' + lesson.id + '  (' + lesson.cells.length + ' 单元)');
